def esc(s: str) -> str:
    return (
        s.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("'", r"\'")
        .replace('"', r"\"")
    )


def write_xml(path: Path, lang_index: int) -> None:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for name, zh, en in ENTRIES:
        val = zh if lang_index == 0 else en
        lines.append(f'    <string name="{name}">{esc(val)}</string>')
    lines.append("</resources>")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    base = Path(__file__).resolve().parents[1] / "app" / "src" / "main" / "res"
    (base / "values-en").mkdir(exist_ok=True)
    write_xml(base / "values" / "strings.xml", 0)
    write_xml(base / "values-en" / "strings.xml", 1)
    print(f"wrote {len(ENTRIES)} strings")


if __name__ == "__main__":
    main()
