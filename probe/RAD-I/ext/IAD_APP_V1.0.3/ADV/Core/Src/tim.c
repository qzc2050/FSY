/**
  * @brief This function handles System tick timer.
  */
void SysTick_Handler(void)
{
    HAL_IncTick();

	if(sys_bits.power_sta == POWER_ON)
	{
		if(sys_bits.run_md == RUN_MODE)
			key_ctr.up_tk++;
		if(key_ctr.sd_cd_tk)
			key_ctr.sd_cd_tk++;

		data_var.day_acc_tk++;    //当日使用总时长，同时也作为其他一些变量的累计时
	}
}

